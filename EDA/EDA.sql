-- Magnitude Analysis
-- -------------------------------------------

-- Find total customers by country

SELECT
	country,
	COUNT(customer_key) AS total_customers
FROM
	dwh_gold.dim_customers
GROUP BY
	country
ORDER BY
	total_customers DESC

-- Find total customers by gender

SELECT
	gender,
	COUNT(customer_key) AS total_customers
FROM
	dwh_gold.dim_customers
GROUP BY
	gender
ORDER BY
	total_customers DESC

-- Find total products by category

SELECT
	category,
	COUNT(product_key) AS total_products
FROM
	dwh_gold.dim_products
GROUP BY
	category
ORDER BY total_products DESC

-- What is the average cost in each category?

SELECT
	category,
	ROUND(AVG(product_cost), 2) AS avg_prd_cost
FROM
	dwh_gold.dim_products
GROUP BY
	category
ORDER BY
	avg_prd_cost DESC

-- What is total revenue generated for each catergory?

SELECT
	p.category,
	SUM(f.sales_amount) AS total_revenue
FROM
	dwh_gold.fact_sales f LEFT JOIN dwh_gold.dim_products p
	ON p.product_key = f.product_key
GROUP BY
	category
ORDER BY
	total_revenue DESC


-- Find total revenue is generated by each customer

SELECT
	c.customer_key,	
	c.first_name,
	c.last_name,
	SUM(f.sales_amount) AS total_revenue
FROM
	dwh_gold.fact_sales f LEFT JOIN dwh_gold.dim_customers c
	ON f.customer_key = c.customer_key
GROUP BY
	c.customer_key,
	c.first_name,
	c.last_name
ORDER BY
	total_revenue DESC

-- What is the distribtion of sold items across countries?

SELECT
	c.country,
	SUM(f.quantity) AS sold_qunatity
FROM
	dwh_gold.fact_sales f JOIN dwh_gold.dim_customers c
	ON f.customer_key = c.customer_key
GROUP BY
	c.country
ORDER BY
	sold_qunatity DESC



-- Ranking Analysis
-- ----------------------------------


-- Which 5 products generate the highest revenue

SELECT
	p.product_name,
	SUM(f.sales_amount) AS total_revenue
FROM
	dwh_gold.dim_products p JOIN dwh_gold.fact_sales f
	ON p.product_key = f.product_key
GROUP BY
	p.product_name 
ORDER BY total_revenue DESC
LIMIT 5

-- same using WINDOW FUNCTION

SELECT
	*
FROM (
	SELECT
		p.product_name,
		SUM(f.sales_amount) AS total_revenue,
		DENSE_RANK() OVER (ORDER BY SUM(f.sales_amount) DESC) AS revenue_rnk
	FROM
		dwh_gold.dim_products p JOIN dwh_gold.fact_sales f
		ON p.product_key = f.product_key
	GROUP BY
		p.product_name)t
WHERE revenue_rnk <= 5;


-- 3 customers with fewest order placed (this will take too long due to LEFT JOIN and then DISTINCT)

SELECT
	c.customer_key,
	c.first_name,
	c.last_name,
	COUNT(DISTINCT f.order_number) AS order_count
FROM
	dwh_gold.dim_customers c LEFT JOIN dwh_gold.fact_sales f
	ON c.customer_key = f.customer_key
GROUP BY
	c.customer_key,
	c.first_name,
	c.last_name
ORDER BY
	order_count ASC
LIMIT 3


-- Optimizing above query to get result much faster
-- Our approach is to use 2 CTE's

WITH order_count AS -- This CTE calculates the total_orders per customer_key and then ORDER BY them and select 3 as per order
(
    SELECT
        customer_key,
        COUNT(DISTINCT order_number) AS total_orders
    FROM dwh_gold.fact_sales
    GROUP BY customer_key
    ORDER BY total_orders ASC, customer_key ASC
    LIMIT 3
),

customer AS -- This CTE will just find the customer first and last name along with all the details of 1st CTE as....
(			-- we used INNER JOIN to find names as per customes_key as LEFT JOIN will show the result for those customers
    SELECT	-- along with these who never made any order and have NULL in their total_orders
        o.*,
        c.first_name,
        c.last_name
    FROM dwh_gold.dim_customers c
    JOIN order_count o
        ON c.customer_key = o.customer_key
)

SELECT *
FROM customer;












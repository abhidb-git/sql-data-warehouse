-- Find the date of first and last order
-- How many years of sales are available

SELECT
	MIN(order_date) AS first_order_date,
	MAX(order_date) AS last_order_date,
	YEAR(MAX(order_date)) - YEAR(MIN(order_date)) AS order_range_years 
FROM
	dwh_gold.fact_sales
	

-- Find youngest and oldest customer
	
SELECT
	MIN(birthdate) AS oldest_birthdate,
	TIMESTAMPDIFF(YEAR, MIN(birthdate), CURRENT_DATE()) AS oldest_age,
	MAX(birthdate) AS youngest_birthdate,
	TIMESTAMPDIFF(YEAR, MAX(birthdate), CURRENT_DATE()) AS youngest_age
FROM
	dwh_gold.dim_customers
	

-- Find the total sales

SELECT SUM(sales_amount) AS total_sales
FROM dwh_gold.fact_sales

-- Find how many items are sold

SELECT SUM(quantity) AS total_qunatity
FROM dwh_gold.fact_sales

-- Find average selling price

SELECT ROUND(AVG(price), 2) AS avg_selling_price
FROM dwh_gold.fact_sales

-- Find the total number of orders

SELECT COUNT(order_number) AS total_orders
FROM dwh_gold.fact_sales

SELECT COUNT(DISTINCT order_number) AS total_orders -- gives more accurate number
FROM dwh_gold.fact_sales

-- Find total number of products

SELECT COUNT(product_key) AS total_products 
FROM dwh_gold.dim_products
	
SELECT COUNT(DISTINCT product_key) AS total_products 
FROM dwh_gold.dim_products

-- Find total number of customers

SELECT COUNT(customer_key) AS total_customers
FROM dwh_gold.dim_customers

-- Find total number of customers that has placed an order

SELECT COUNT(DISTINCT customer_key) AS customers_placed_orders
FROM dwh_gold.dim_customers



